#!/usr/bin/env bash
# Bring up every PCAN-USB Pro FD channel and resolve USB-path → OpenArm role.
#
# Writes a sourceable env file at $OUT_ENV (default ~/.config/openarm/can_map.env)
# with stable role variables:
#   OPENARM_LEADER_R   OPENARM_LEADER_L
#   OPENARM_FOLLOWER_R OPENARM_FOLLOWER_L
#
# Mapping is keyed off the USB physical port path because the two PEAK adapters
# have IDENTICAL hw serial in udev — only the USB port distinguishes them.
#
# USB port → role (this is the setup-confirmed mapping for kota-ueda's PC):
#   usb-0:5   = Adapter A = Leader   (CH1 = R, CH2 = L)
#   usb-0:12  = Adapter B = Follower (CH1 = R, CH2 = L)
#
# CH ordering within an adapter: the lower kernel ifindex on a given USB path
# is CH1; the higher is CH2. The PEAK driver brings them up in deterministic
# order, so this holds across reboots as long as the adapters stay in the same
# physical USB ports.

set -euo pipefail

BITRATE=1000000
DBITRATE=5000000

# Resolve target home: when run via sudo, write to invoking user's home, not /root.
if [[ -n "${SUDO_USER:-}" ]]; then
  TARGET_HOME=$(getent passwd "$SUDO_USER" | cut -d: -f6)
else
  TARGET_HOME="$HOME"
fi
OUT_ENV="${OUT_ENV:-$TARGET_HOME/.config/openarm/can_map.env}"

# USB port substring → role-side for CH1 / CH2
# Mapping RE-CONFIRMED 2026-06-04 after both adapters moved USB ports (5→6, 12→1).
# Verified by unplug test: pulling the Type-C adapter dropped can0/can1, so:
#   USB 1-6 (Type-C cable) → Leader pair    (CH1=can0=R, CH2=can1=L)
#   USB 1-1 (Type-A cable) → Follower pair  (CH1=can2=R, CH2=can3=L)
# Ground truth = which canN disappear on unplug, not cable tracing.
declare -A PORT_ROLE_CH1=(
  ["usb-0:6"]="LEADER_R"
  ["usb-0:1"]="FOLLOWER_R"
)
declare -A PORT_ROLE_CH2=(
  ["usb-0:6"]="LEADER_L"
  ["usb-0:1"]="FOLLOWER_L"
)

need_sudo() {
  if [[ $EUID -ne 0 ]]; then
    echo "[openarm_canup] re-executing under sudo..."
    exec sudo -E env OUT_ENV="$OUT_ENV" "$0" "$@"
  fi
}

bring_up_all() {
  local ifs
  mapfile -t ifs < <(ip -brief link show type can 2>/dev/null | awk '{print $1}')
  for IF in "${ifs[@]}"; do
    echo "[openarm_canup] configuring $IF ..."
    openarm-can-configure-socketcan "$IF" -fd -b "$BITRATE" -d "$DBITRATE" >/dev/null
  done
}

resolve_roles() {
  # For each USB path, collect canN ifs sorted by ifindex; lowest = CH1.
  declare -A BY_PORT
  for SYS in /sys/class/net/can*; do
    [[ -e "$SYS" ]] || continue
    local ifname idx path key
    ifname=$(basename "$SYS")
    idx=$(cat "$SYS/ifindex")
    # Extract usb-0:N from ID_PATH via udevadm
    path=$(udevadm info -q property "$SYS" 2>/dev/null | sed -n 's/^ID_PATH=//p')
    key=$(echo "$path" | grep -oE 'usb-0:[0-9]+' | head -1)
    [[ -z "$key" ]] && continue
    BY_PORT[$key]+="$idx $ifname"$'\n'
  done

  mkdir -p "$(dirname "$OUT_ENV")"
  : > "$OUT_ENV"
  echo "# Generated by openarm_canup.sh on $(date -Iseconds)" >> "$OUT_ENV"

  for port in "${!BY_PORT[@]}"; do
    # Sort lines by ifindex
    mapfile -t lines < <(printf "%s" "${BY_PORT[$port]}" | sort -n)
    local ch1_if ch2_if r1 r2
    ch1_if=$(echo "${lines[0]}" | awk '{print $2}')
    ch2_if=$(echo "${lines[1]:-}" | awk '{print $2}')
    r1="${PORT_ROLE_CH1[$port]:-UNKNOWN1}"
    r2="${PORT_ROLE_CH2[$port]:-UNKNOWN2}"
    [[ -n "$ch1_if" ]] && echo "export OPENARM_${r1}=${ch1_if}" >> "$OUT_ENV"
    [[ -n "$ch2_if" ]] && echo "export OPENARM_${r2}=${ch2_if}" >> "$OUT_ENV"
    echo "[openarm_canup] $port  -> CH1=$ch1_if ($r1)  CH2=$ch2_if ($r2)"
  done

  # Make readable by invoking user when run via sudo
  if [[ -n "${SUDO_USER:-}" ]]; then
    chown "$SUDO_USER:$SUDO_USER" "$OUT_ENV" "$(dirname "$OUT_ENV")"
  fi
  echo
  echo "[openarm_canup] wrote $OUT_ENV:"
  cat "$OUT_ENV"
}

need_sudo "$@"
bring_up_all
resolve_roles
